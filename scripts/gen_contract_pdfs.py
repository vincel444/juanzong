def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    jobs = [
        ("劳动合同书-样例A.pdf", CONTRACT_A, 2),
        ("房屋租赁合同-样例B.pdf", CONTRACT_B, 2),
        ("软件开发服务协议-样例C.pdf", CONTRACT_C, 2),
    ]
    for filename, spec, min_pages in jobs:
        pdf = new_pdf()
        render(pdf, spec["title"], spec["meta"], spec["articles"])
        path = OUT_DIR / filename
        pdf.output(str(path))
        # 立即用 pypdf 回验：页数与关键文本可抽取（模拟 retrieval._extract_pdf）
        from pypdf import PdfReader

        reader = PdfReader(str(path))
        text = "".join((p.extract_text() or "") for p in reader.pages)
        first_clause = spec["articles"][0][0][:4]
        assert len(reader.pages) >= min_pages, f"{filename} 页数异常: {len(reader.pages)}"
        assert "第一条" in text and first_clause in text, f"{filename} 文本抽取异常"
        print(f"OK  {filename}  {len(reader.pages)} 页  {path.stat().st_size // 1024} KB")
    print("全部生成完毕 ->", OUT_DIR)


if __name__ == "__main__":
    main()
